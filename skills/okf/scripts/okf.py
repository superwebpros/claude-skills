def add_log_entry(path, date, kind, message):
    lines = open(path, encoding="utf-8").read().splitlines() if os.path.exists(path) else ["# Update Log", ""]
    entry = f"* **{kind}**: {message}"
    heads = [(i, l[3:].strip()) for i, l in enumerate(lines) if l.startswith("## ")]
    for n, (i, h) in enumerate(heads):
        if h == date:
            end = heads[n + 1][0] if n + 1 < len(heads) else len(lines)
            while end > i + 1 and not lines[end - 1].strip():
                end -= 1
            lines.insert(end, entry)
            break
        if DATE_RE.match(h) and h < date:
            lines[i:i] = [f"## {date}", entry, ""]
            break
    else:
        while lines and not lines[-1].strip():
            lines.pop()
        lines += ["", f"## {date}", entry]
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines).rstrip("\n") + "\n")


