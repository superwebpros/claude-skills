def infer_type(rel, fm, rules, default):
    for glob, t in rules:
        if fnmatch.fnmatch(rel, glob):
            return t, "rule"
    for k in ("kind", "category", "layout", "doc_type", "doctype"):
        if isinstance(fm.get(k), str) and fm[k].strip():
            return humanize(fm[k]).title() if fm[k].islower() else fm[k], f"existing-field:{k}"
    parts = rel.lower().split("/")
    for seg in [parts[-1]] + parts[-2::-1]:
        seg = re.sub(r"\.md$", "", seg).replace("_", " ").replace(".", " ")
        for pat, t in TYPE_HEURISTICS:
            if re.search(pat, seg):
                return t, "heuristic"
    return default, "default"


def first_sentence(body):
    s = strip_code(body)
    s = re.sub(r"<!--.*?-->", "", s, flags=re.S)
    para = []
    for line in s.splitlines():
        t = line.strip()
        if not t:
            if para:
                break
            continue
        if re.match(r"^(#|>|\||[*+-]\s|\d+[.)]\s|!\[|<|---|===|\[\^)", t):
            if para:
                break
            continue
        para.append(t)
    if not para:
        return None
    text = " ".join(para)
    text = re.sub(r"!?\[([^\]]*)\]\([^)]*\)", r"\1", text)
    text = re.sub(r"[*_]{1,3}([^*_]+)[*_]{1,3}", r"\1", text)
    text = re.sub(r"\[\^[^\]]+\]", "", text).strip()
    m = re.match(r"(.+?[.!?])(\s|$)", text)
    sent = m.group(1) if m else text
    return sent if len(sent) <= 200 else sent[:197].rstrip() + "..."


def file_time(path):
    try:
        out = subprocess.run(["git", "log", "-1", "--format=%cI", "--", os.path.basename(path)],
                             cwd=os.path.dirname(path), capture_output=True, text=True, timeout=10).stdout.strip()
        if out:
            return utc_z(datetime.fromisoformat(out)), "git"
    except Exception:
        pass
    return utc_z(datetime.fromtimestamp(os.path.getmtime(path), timezone.utc)), "mtime"


def slug(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")[:40] or "source"


def parse_citations(body):
    sec = find_section(body, "citations")
    if not sec:
        return None, []
    sources, seen = [], set()
    for line in body[sec[0]:sec[1]].splitlines():
        m = re.match(r"^\s*(?:[-*+]|\d+[.)])\s+(.+)$", line)
        if not m:
            continue
        item = m.group(1).strip()
        lm = re.search(r"\[([^\]]+)\]\(([^)\s]+)\)", item)
        um = re.search(r"https?://\S+", item)
        if lm:
            title, res = lm.group(1).strip(), lm.group(2)
        elif um:
            res = um.group(0).rstrip(").,;")
            title = item.replace(um.group(0), "").strip(" -:,") or None
        else:
            title, res = None, item
        base = slug(title) if title else slug(re.sub(r"^https?://(www\.)?", "", res).rstrip("/").split("/")[-1])
        sid, n = base, 2
        while sid in seen:
            sid, n = f"{base}-{n}", n + 1
        seen.add(sid)
        e = {"id": sid, "resource": res}
        if title:
            e["title"] = title
        sources.append(e)
    return sec, sources


def looks_like_prose(d):
    s = strip_code(d.body)
    if isinstance(fm_dict(d).get("type"), str):
        return True
    items = len(LIST_LINK_RE.findall(s))
    prose = sum(1 for l in s.splitlines() if l.strip() and not re.match(r"^\s*(#|[*+-]\s|\d+[.)]\s)", l))
    return items == 0 and prose > 0


def cmd_plan(a):
    b = Bundle(a.root, a.exclude)
    rules = []
    for r in a.rule:
        if "=" not in r:
            sys.exit(f"--rule must look like 'GLOB=Type' (got {r!r})")
        g, t = r.split("=", 1)
        rules.append((g.strip(), t.strip()))
    files = []
    for rel, d in sorted(b.docs.items()):
        name = posixpath.basename(rel)
        item = {"path": rel, "actions": [], "notes": []}
        if name in RESERVED:
            bad_log = name == "log.md" and any(
                not DATE_RE.match(h.strip()) for h in re.findall(r"^##[ \t]+(.+)$", strip_code(d.body), re.M))
            if (name == "index.md" and looks_like_prose(d)) or bad_log:
                stem = posixpath.basename(posixpath.dirname(rel)) or "bundle"
                inbound = sum(1 for o in b.docs.values() if any(
                    resolve(o.rel, u) == rel for u in LINK_RE.findall(strip_code(o.body))))
                item["actions"].append("review-reserved")
                item["suggested_rename"] = rjoin(posixpath.dirname(rel), f"{stem}-{'overview' if name == 'index.md' else 'history'}.md")
                item["rename_to"] = None
                fix = ("rewrite it as `* [Title](url) - description` sections (or run `okf.py index --force`)" if name == "index.md"
                       else "rewrite its `##` headings as YYYY-MM-DD dates, newest first")
                item["notes"].append(f"{name} is reserved (spec 3.1) but doesn't follow spec {'8' if name == 'index.md' else '9'}. "
                                     f"Either {fix}, or, if it is really a concept, set rename_to and re-run plan to give it frontmatter "
                                     f"({inbound} inbound link(s) would need updating).")
                files.append(item)
            continue
        if d.has_fm and (d.fm_error or not isinstance(d.fm, dict)):
            item["actions"].append("fix-frontmatter-manually")
            item["notes"].append(d.fm_error or "Frontmatter is not a YAML mapping.")
            files.append(item)
            continue
        fm = fm_dict(d)
        add = {}
        if not (isinstance(fm.get("type"), str) and fm["type"].strip()):
            add["type"], item["type_source"] = infer_type(rel, fm, rules, a.default_type)
        if "title" not in fm:
            add["title"] = concept_title(d)
        if "description" not in fm:
            desc = next((fm[k] for k in ("summary", "excerpt", "abstract") if isinstance(fm.get(k), str)), None) or first_sentence(d.body)
            if desc:
                add["description"] = " ".join(desc.split())
            else:
                item["notes"].append("No description could be derived; write one.")
        if isinstance(fm.get("tags"), str):
            item["fix"] = {"tags": [t.strip() for t in re.split(r"[,;]", fm["tags"]) if t.strip()]}
        if a.by and "generated" not in fm and "timestamp" not in fm:
            at, src = file_time(b.abs(rel))
            add["generated"] = {"by": a.by, "at": at}
            item["notes"].append(f"generated.at taken from {src}.")
        if add:
            item["actions"].append("add-frontmatter" if not d.has_fm else "add-fields")
            item["add"] = add
        if item.get("fix"):
            item["actions"].append("fix-fields")
        migrate = {}
        if "timestamp" in fm and "generated" not in fm:
            ts = fm["timestamp"]
            dt = parse_dt(str(ts)) or (parse_dt(str(ts) + "Z") if re.match(r"^\d{4}-\d{2}-\d{2}T[\d:.]+$", str(ts)) else None)
            if dt is None and DATE_RE.match(str(ts)):
                dt = parse_dt(f"{ts}T00:00:00Z")
            migrate["generated"] = {"by": a.by, "at": utc_z(dt) if dt else str(ts)}
            if not a.by:
                item["notes"].append("Set migrate.generated.by to an actor (e.g. human:<id>) or the timestamp migration is skipped.")
        sec, cites = parse_citations(d.body)
        if sec:
            if fm.get("sources"):
                item["notes"].append("Has both `# Citations` and `sources`; merge by hand.")
            else:
                migrate["sources"] = cites
                item["notes"].append("Citations become `sources`; add keyed footnotes ([^id]) where claims rely on them.")
        if migrate:
            item["actions"].append("migrate-v0.1")
            item["migrate"] = migrate
        if item["actions"]:
            files.append(item)
    counts = Counter(act for f in files for act in f["actions"])
    type_sources = Counter(f.get("type_source") for f in files if f.get("type_source"))
    plan = {"okf_plan": 1, "root": b.root, "created": utc_z(now_utc()), "by": a.by,
            "summary": {"files_scanned": len(b.docs), "files_to_change": len(files), "actions": dict(counts),
                        "type_sources": dict(type_sources),
                        "proposed_types": dict(Counter(f["add"]["type"] for f in files if "type" in f.get("add", {})))},
            "files": files}
    text = json.dumps(plan, indent=2, ensure_ascii=False)
    if a.out:
        with open(a.out, "w", encoding="utf-8") as f:
            f.write(text + "\n")
        s = plan["summary"]
        print(f"plan written to {a.out}: {s['files_to_change']}/{s['files_scanned']} files to change")
        print(f"  actions: {s['actions']}")
        print(f"  proposed types: {s['proposed_types']}")
        print(f"  type sources: {s['type_sources']}  (review 'heuristic' and 'default' entries)")
    else:
        print(text)
    return 0


HEAD_KEYS = ("type", "title", "description")


def insert_fields(fm_raw, fields):
    """Insert new top-level keys without disturbing existing text: `type` first,
    title/description after the existing head keys, everything else at the end."""
    lines = fm_raw.splitlines()
    for k, v in fields.items():
        block = emit(k, v)
        if k == "type":
            lines[0:0] = block
        elif k in HEAD_KEYS:
            at = 0
            for i, line in enumerate(lines):
                if re.match(rf"^({'|'.join(HEAD_KEYS)})\s*:", line):
                    at = i + 1
                    while at < len(lines) and re.match(r"^[ \t-]", lines[at]):
                        at += 1
            lines[at:at] = block
        else:
            lines += block
    return "\n".join(lines) + "\n"


def _rebuild(fm_raw, body):
    if fm_raw and not fm_raw.endswith("\n"):
        fm_raw += "\n"
    return f"---\n{fm_raw}---\n{body}"


def cmd_apply(a):
    with open(a.plan, encoding="utf-8") as f:
        plan = json.load(f)
    root = a.root or plan["root"]
    done, skipped = 0, []
    for item in plan["files"]:
        rel = item["path"]
        path = os.path.join(root, rel)
        if not os.path.exists(path):
            skipped.append((rel, "file no longer exists"))
            continue
        with open(path, encoding="utf-8") as f:
            text = f.read()
        d = parse_doc(rel, text)
        new = text
        acts = item.get("actions", [])
        add = {k: v for k, v in (item.get("add") or {}).items() if v not in (None, "")}
        if "add-frontmatter" in acts:
            if d.has_fm:
                skipped.append((rel, "already has frontmatter; re-run plan"))
                continue
            if not add.get("type"):
                skipped.append((rel, "no type in plan"))
                continue
            new = emit_block(add) + ("\n" if not d.body.startswith("\n") else "") + d.body
        elif "add-fields" in acts and d.has_fm and isinstance(d.fm, dict):
            missing = {k: v for k, v in add.items() if k not in d.fm}
            if missing:
                new = _rebuild(insert_fields(d.fm_raw, missing), d.body)
        fix = item.get("fix") or {}
        if "fix-fields" in acts and fix:
            d = parse_doc(rel, new)
            fm_raw = d.fm_raw
            for k, v in fix.items():
                fm_raw = re.sub(rf"^{re.escape(k)}\s*:.*$", lambda _m: "\n".join(emit(k, v)), fm_raw, count=1, flags=re.M)
            new = _rebuild(fm_raw, d.body) if d.has_fm else new
        mig = item.get("migrate") or {}
        if "migrate-v0.1" in acts and mig:
            d = parse_doc(rel, new)
            fm_raw, body = d.fm_raw, d.body
            g = mig.get("generated")
            if g and g.get("by") and isinstance(d.fm, dict) and "generated" not in d.fm:
                fm_raw = re.sub(r"^timestamp\s*:.*$", emit("generated", {"by": g["by"], "at": g["at"]})[0], fm_raw, count=1, flags=re.M)
            elif g:
                skipped.append((rel, "timestamp kept: migrate.generated.by not set"))
            src = mig.get("sources")
            if src and isinstance(d.fm, dict) and "sources" not in d.fm:
                fm_raw = (fm_raw if fm_raw.endswith("\n") or not fm_raw else fm_raw + "\n") + "\n".join(emit("sources", src)) + "\n"
                sec = find_section(body, "citations")
                if sec:
                    rest = body[sec[1]:].lstrip("\n")
                    body = body[: sec[0]].rstrip("\n") + ("\n\n" + rest if rest else "").rstrip("\n") + "\n"
            new = _rebuild(fm_raw, body) if d.has_fm else new
        target = item.get("rename_to")
        if new != text:
            check = parse_doc(rel, new)
            if check.fm_error or not isinstance(check.fm, dict):
                skipped.append((rel, f"result would not parse ({check.fm_error}); left untouched"))
                continue
            if not a.dry_run:
                with open(path, "w", encoding="utf-8") as f:
                    f.write(new)
            print(f"{'would edit' if a.dry_run else 'edited'} {rel}")
            done += 1
        if target:
            tpath = os.path.join(root, target)
            if os.path.exists(tpath):
                skipped.append((rel, f"rename target {target} exists"))
            else:
                if not a.dry_run:
                    os.makedirs(os.path.dirname(tpath) or ".", exist_ok=True)
                    os.rename(path, tpath)
                print(f"{'would rename' if a.dry_run else 'renamed'} {rel} -> {target}")
                done += 1
    for rel, why in skipped:
        print(f"skipped {rel}: {why}")
    print(f"{done} change(s) {'planned' if a.dry_run else 'applied'}, {len(skipped)} skipped")
    if not a.dry_run and done:
        print("next: okf.py index ROOT && okf.py audit ROOT")
    return 0


