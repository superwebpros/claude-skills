def concept_title(d):
    fm = fm_dict(d)
    if isinstance(fm.get("title"), str) and fm["title"].strip():
        return fm["title"].strip()
    m = re.search(r"^#[ \t]+(.+?)[ \t]*#*[ \t]*$", strip_code(d.body), re.M)
    return m.group(1).strip() if m else humanize(posixpath.basename(d.rel))


def _esc(s):
    return s.replace("[", "\\[").replace("]", "\\]")


def _entry(title, url, desc):
    line = f"* [{_esc(title)}]({url})"
    if desc:
        line += " - " + " ".join(str(desc).split())
    return line


def build_index(b, rel_dir, group_by, version):
    subdirs, mds = b.dirs[rel_dir]
    concepts = [b.docs[rjoin(rel_dir, f)] for f in mds if is_concept(f) and rjoin(rel_dir, f) in b.docs]
    groups = {}
    deprecated = []
    for d in sorted(concepts, key=lambda d: concept_title(d).lower()):
        fm = fm_dict(d)
        e = _entry(concept_title(d), posixpath.basename(d.rel), fm.get("description"))
        if fm.get("status") == "deprecated":
            deprecated.append(e)
            continue
        key = str(fm.get("type") or "Concepts") if group_by == "type" else "Concepts"
        groups.setdefault(key, []).append(e)
    dir_entries = []
    for sd in subdirs:
        r = rjoin(rel_dir, sd)
        sub = b.subtree_concepts(r)
        if not sub:
            continue
        desc = None
        for cand in ("README.md", "overview.md", f"{sd}.md"):
            cd = b.docs.get(rjoin(r, cand))
            if cd and isinstance(fm_dict(cd).get("description"), str):
                desc = fm_dict(cd)["description"]
                break
        if not desc:
            types = Counter(str(fm_dict(b.docs[x]).get("type") or "untyped") for x in sub)
            desc = f"{len(sub)} concept{'s' * (len(sub) != 1)} ({', '.join(t for t, _ in types.most_common(3))})"
        dir_entries.append(_entry(humanize(sd), f"{sd}/", desc))
    parts = []
    if version:
        parts.append(f'---\nokf_version: "{version}"\n---\n')
    parts.append(GEN_LINE + "\n")
    for key in sorted(groups):
        parts.append(f"# {key}\n\n" + "\n".join(groups[key]) + "\n")
    if dir_entries:
        parts.append("# Directories\n\n" + "\n".join(dir_entries) + "\n")
    if deprecated:
        parts.append("# Deprecated\n\n" + "\n".join(deprecated) + "\n")
    if not groups and not dir_entries and not deprecated:
        parts.append("# Concepts\n\n_No concepts yet. Add one with `okf.py new`._\n")
    return "\n".join(parts)


def cmd_index(a):
    b = Bundle(a.root, a.exclude)
    root_idx = b.docs.get("index.md")
    existing_version = fm_dict(root_idx).get("okf_version") if root_idx else None
    version = None if a.no_version else (a.okf_version or (str(existing_version) if existing_version else OKF_VERSION))
    changed, skipped, unchanged = [], [], 0
    for rel_dir in sorted(b.dirs):
        if not b.subtree_concepts(rel_dir) and rel_dir != "":
            continue
        rel = rjoin(rel_dir, "index.md")
        content = build_index(b, rel_dir, a.group_by, version if rel_dir == "" else None)
        old = b.docs[rel].text if rel in b.docs else None
        if old is not None and GEN_MARKER not in old and not a.force:
            skipped.append(rel)
            continue
        if old == content:
            unchanged += 1
            continue
        changed.append(rel)
        if not a.check:
            with open(b.abs(rel), "w", encoding="utf-8") as f:
                f.write(content)
    verb = "would update" if a.check else "wrote"
    for r in changed:
        print(f"{verb} {r}")
    for r in skipped:
        print(f"skipped {r} (hand-curated: no okf:generated marker; --force to overwrite)")
    print(f"{len(changed)} {verb}, {unchanged} unchanged, {len(skipped)} skipped")
    return 1 if a.check and changed else 0


