@dataclass
class Finding:
    severity: str
    code: str
    path: str
    message: str
    line: int = 0


SEV_ORDER = {"error": 0, "warning": 1, "info": 2}


def audit(b, now):
    out = []

    def add(sev, code, path, msg, line=0):
        out.append(Finding(sev, code, path, msg, line))

    for rel in b.unreadable:
        add("error", "not-utf8", rel, "File is not UTF-8; OKF concepts must be UTF-8 markdown (spec 4).")

    for rel, d in sorted(b.concepts().items()):
        _audit_concept(b, d, add, now)

    for rel_dir in sorted(b.dirs):
        _audit_reserved(b, rel_dir, add)

    out.sort(key=lambda f: (SEV_ORDER[f.severity], f.path, f.line, f.code))
    return out, _summary(b, out, now)


def _check_dt(add, rel, line, key, val):
    if parse_dt(val) is None:
        add("warning", "bad-datetime", rel,
            f"`{key}` must be an ISO 8601 datetime with an explicit UTC offset, e.g. 2026-06-30T14:00:00Z (got {val!r}).", line)
        return None
    return parse_dt(val)


def _check_actor(add, rel, line, key, val):
    if not isinstance(val, str) or not ACTOR_RE.match(val):
        add("warning", "bad-actor", rel,
            f"`{key}` should be an actor: `<producer>/<version>`, `human:<id>`, or `process:<id>` (got {val!r}) (spec 7).", line)


def _check_path(b, add, d, key, val, line):
    if not isinstance(val, str) or not val.strip():
        add("warning", "missing-path-target", d.rel, f"`{key}` should be a path or URL.", line)
        return
    p = resolve(d.rel, val)
    if p is None:
        return
    if p.startswith(".."):
        add("warning", "path-outside-bundle", d.rel, f"`{key}` ({val}) points outside the bundle.", line)
    elif b.exists(p):
        return
    elif not val.startswith("/") and b.exists(resolve(d.rel, val, from_root=True)):
        add("info", "path-resolved-from-root", d.rel,
            f"`{key}` ({val}) only exists relative to the bundle root; write `/{val}` so it resolves unambiguously (spec 6.2).", line)
    else:
        add("warning", "missing-path-target", d.rel, f"`{key}` ({val}) does not exist in the bundle.", line)


def _audit_concept(b, d, add, now):
    rel = d.rel
    name = posixpath.basename(rel)
    if name.lower() in RESERVED:
        add("info", "reserved-name-case", rel, f"`{name}` differs from reserved `{name.lower()}` only by case; avoid confusion.")
    if not d.has_fm:
        add("error", "missing-frontmatter", rel, "No YAML frontmatter; every concept needs at least `type` (spec 4.1, 11).", 1)
    elif d.fm_error:
        add("error", "invalid-frontmatter", rel, f"Frontmatter is not parseable YAML: {d.fm_error}", 1)
    elif not isinstance(d.fm, dict):
        add("error", "invalid-frontmatter", rel, "Frontmatter must be a YAML mapping.", 1)
    fm = fm_dict(d)
    if isinstance(d.fm, dict) or (d.has_fm and not d.fm_error and d.fm == {}):
        t = fm.get("type")
        if not isinstance(t, str) or not t.strip():
            add("error", "missing-type", rel, "Frontmatter needs a non-empty string `type` (spec 4.1, 11).", fm_line(d, "type"))
        if "title" not in fm:
            add("info", "missing-title", rel, "No `title` (recommended; consumers fall back to the filename).")
        desc = fm.get("description")
        if desc is None:
            add("warning", "missing-description", rel, "No `description` (recommended; used by index.md, search, previews).")
        elif not isinstance(desc, str):
            add("warning", "missing-description", rel, "`description` should be a one-line string.", fm_line(d, "description"))
        elif "\n" in desc.strip() or len(desc) > 240:
            add("info", "long-description", rel, "`description` should be a single sentence.", fm_line(d, "description"))
        if "tags" in fm and not (isinstance(fm["tags"], list) and all(isinstance(x, str) for x in fm["tags"])):
            add("warning", "tags-not-list", rel, "`tags` should be a YAML list of strings, e.g. [sales, revenue].", fm_line(d, "tags"))
        if "status" in fm and fm["status"] not in STATUSES:
            add("warning", "invalid-status", rel, f"`status` must be one of {', '.join(STATUSES)} (got {fm['status']!r}).", fm_line(d, "status"))
        if "stale_after" in fm:
            dt = _check_dt(add, rel, fm_line(d, "stale_after"), "stale_after", fm["stale_after"])
            if dt and now >= dt:
                add("warning", "stale", rel, f"Stale since {fm['stale_after']} (now >= stale_after); re-verify and push it forward (spec 5.5).", fm_line(d, "stale_after"))
        if "timestamp" in fm:
            add("warning", "legacy-timestamp", rel, "v0.1 `timestamp` is superseded by `generated: { by, at }` (spec 13.1).", fm_line(d, "timestamp"))
        _audit_trust(d, fm, add)
        source_ids = _audit_sources(d, fm, add)
        if fm.get("type") == AC_TYPE:
            _audit_ac(b, d, fm, add)
    else:
        source_ids = set()
    _audit_body(b, d, add, source_ids)


def _audit_trust(d, fm, add):
    rel = d.rel
    if "generated" in fm:
        g, ln = fm["generated"], fm_line(d, "generated")
        if not isinstance(g, dict):
            add("warning", "bad-generated", rel, "`generated` should be a mapping `{ by, at }` (spec 5.2).", ln)
        else:
            if "by" not in g:
                add("warning", "bad-generated", rel, "`generated.by` is required within `generated` (spec 5.2).", ln)
            else:
                _check_actor(add, rel, ln, "generated.by", g["by"])
            if "at" in g:
                _check_dt(add, rel, ln, "generated.at", g["at"])
    if "verified" in fm:
        v, ln = fm["verified"], fm_line(d, "verified")
        entries = [v] if isinstance(v, dict) else v
        if not isinstance(entries, list):
            add("warning", "bad-verified", rel, "`verified` should be a list of `{ by, at }` (or one mapping) (spec 5.2).", ln)
            return
        for e in entries:
            if not isinstance(e, dict) or "by" not in e or "at" not in e:
                add("warning", "bad-verified", rel, f"Each `verified` entry needs `by` and `at` (got {e!r}).", ln)
                continue
            _check_actor(add, rel, ln, "verified.by", e["by"])
            _check_dt(add, rel, ln, "verified.at", e["at"])


def _audit_sources(d, fm, add):
    rel, ids = d.rel, set()
    if "usage_window" in fm:
        _check_window(add, rel, fm_line(d, "usage_window"), fm["usage_window"])
    if "sources" not in fm:
        return ids
    src, ln = fm["sources"], fm_line(d, "sources")
    if not isinstance(src, list):
        add("warning", "bad-sources", rel, "`sources` should be a list of entries with `resource` (spec 5.1).", ln)
        return ids
    for e in src:
        if not isinstance(e, dict) or not e.get("resource"):
            add("warning", "bad-sources", rel, f"Each `sources` entry needs a `resource` (got {e!r}).", ln)
            continue
        sid = e.get("id")
        if sid is not None:
            if str(sid) in ids:
                add("warning", "duplicate-source-id", rel, f"Duplicate sources id `{sid}`.", ln)
            ids.add(str(sid))
        if "usage_count" in e and not (isinstance(e["usage_count"], int) and not isinstance(e["usage_count"], bool) and e["usage_count"] >= 0):
            add("warning", "bad-sources", rel, f"`usage_count` should be a non-negative integer (source {sid or e['resource']}).", ln)
        if "usage_count" in e and "usage_window" not in fm and "usage_window" not in e:
            add("info", "usage-without-window", rel, f"`usage_count` on {sid or e['resource']} has no `usage_window` framing it (spec 5.1).", ln)
        if "last_modified" in e:
            _check_dt(add, rel, ln, "sources.last_modified", e["last_modified"])
        if "usage_window" in e:
            _check_window(add, rel, ln, e["usage_window"])
    return ids


def _check_window(add, rel, ln, w):
    if not isinstance(w, dict) or "from" not in w or "to" not in w:
        add("warning", "bad-sources", rel, "`usage_window` should be `{ from, to }` datetimes (spec 5.1).", ln)
        return
    _check_dt(add, rel, ln, "usage_window.from", w["from"])
    _check_dt(add, rel, ln, "usage_window.to", w["to"])


def _audit_ac(b, d, fm, add):
    rel = d.rel
    if not fm.get("runtime"):
        add("warning", "ac-missing-runtime", rel, "Attested Computation requires `runtime` (spec 10.2).", 1)
    params = fm.get("parameters")
    if params is not None:
        good = isinstance(params, list) and all(
            isinstance(p, dict) and {"name", "type", "required"} <= set(p) for p in params)
        if not good:
            add("warning", "ac-bad-parameters", rel, "`parameters` entries need `{ name, type, required }` (spec 10.2).", fm_line(d, "parameters"))
    sec = find_section(d.body, "computation")
    fences = 0
    if sec:
        section = d.body[sec[0]:sec[1]]
        fences = len(FENCE_RE.findall(section)) or (1 if re.search(r"(^|\n)\s*\n(?: {4}|\t)\S", section) else 0)
    if "computation" in fm:
        _check_path(b, add, d, "computation", fm["computation"], fm_line(d, "computation"))
        if fences:
            add("warning", "ac-ambiguous-computation", rel, "Both `computation` and an inline `# Computation` block; use one (spec 10.3).")
    elif not fences:
        add("warning", "ac-no-computation", rel, "No computation: add a fenced block under `# Computation` or set `computation:` to a file (spec 10.3).")
    elif fences > 1:
        add("warning", "ac-multiple-fences", rel, "`# Computation` should hold a single fenced code block (spec 10.3).")
    for part in ("executor", "attester"):
        v = fm.get(part)
        if v is None:
            add("info", f"ac-no-{part}", rel, f"No `{part}`; consumers can't {'run' if part == 'executor' else 'check'} this computation (spec 10.2).")
            continue
        if not isinstance(v, dict) or not v.get("resource"):
            add("warning", f"ac-bad-{part}", rel, f"`{part}` needs a `resource` (spec 10.2).", fm_line(d, part))
            continue
        _check_path(b, add, d, f"{part}.resource", v["resource"], fm_line(d, part))
        if part == "executor" and not isinstance(v.get("receipt"), list):
            add("warning", "ac-bad-executor", rel, "`executor.receipt` should list the fields a run returns, e.g. [job_id, executed_sql, result].", fm_line(d, part))


def _audit_body(b, d, add, source_ids):
    rel, s = d.rel, strip_code(d.body)
    if find_section(d.body, "citations"):
        add("warning", "legacy-citations", rel, "v0.1 `# Citations` list is superseded by frontmatter `sources` + keyed footnotes (spec 13.1).")
    labels = set(FN_REF_RE.findall(s)) | set(FN_DEF_RE.findall(s))
    if labels and source_ids:
        for lab in sorted(labels - source_ids):
            add("warning", "footnote-unkeyed", rel, f"Footnote [^{lab}] matches no `sources[].id`; key footnotes to source ids (spec 5.1).")
    elif labels and not source_ids:
        add("info", "footnotes-without-sources", rel, "Body has footnotes but no keyed `sources`; move attribution to `sources` with ids (spec 5.1).")
    for m in LINK_RE.finditer(s):
        p = resolve(rel, m.group(1))
        if p is None or p.startswith(".."):
            continue
        if not b.exists(p):
            line = d.body_line + s.count("\n", 0, m.start())
            add("info", "broken-link", rel, f"Link target `{m.group(1)}` does not exist (tolerated: may be unwritten knowledge) (spec 6.1).", line)


def _audit_reserved(b, rel_dir, add):
    subdirs, mds = b.dirs[rel_dir]
    idx_rel, log_rel = rjoin(rel_dir, "index.md"), rjoin(rel_dir, "log.md")
    has_concepts = bool(b.subtree_concepts(rel_dir))
    if idx_rel in b.docs:
        d = b.docs[idx_rel]
        if d.has_fm:
            fm = fm_dict(d)
            if rel_dir:
                add("error", "index-frontmatter", idx_rel, "Only the bundle-root index.md may carry frontmatter (spec 8).", 1)
            elif d.fm_error or not isinstance(d.fm, dict) or set(fm) - {"okf_version"}:
                add("error", "index-frontmatter", idx_rel, "Root index.md frontmatter may only hold `okf_version` (spec 8, 12).", 1)
            elif "okf_version" in fm and not isinstance(fm["okf_version"], str):
                add("warning", "okf-version-unquoted", idx_rel, 'Quote the version so YAML keeps it a string: okf_version: "0.2".', 2)
        s = strip_code(d.body)
        items = LIST_LINK_RE.findall(s)
        if has_concepts and (not items or not HEADING_RE.search(s)):
            add("warning", "index-structure", idx_rel, "index.md should be headed sections of `* [Title](url) - description` items (spec 8).")
        linked = {resolve(idx_rel, u) for u, _ in items} | {resolve(idx_rel, u) for u in LINK_RE.findall(s)}
        linked = {p.rstrip("/") for p in linked if p is not None}
        linked |= {posixpath.dirname(p) for p in linked if p.endswith("/index.md") or p.endswith("index.md")}
        for f in mds:
            r = rjoin(rel_dir, f)
            if is_concept(r) and r not in linked:
                add("warning", "index-missing-entry", idx_rel, f"Concept `{f}` is not listed; run `okf.py index` or add it.")
        for sd in subdirs:
            r = rjoin(rel_dir, sd)
            if b.subtree_concepts(r) and r not in linked:
                add("warning", "index-missing-entry", idx_rel, f"Subdirectory `{sd}/` is not listed.")
        for u, _ in items:
            p = resolve(idx_rel, u)
            if p is not None and not p.startswith("..") and not b.exists(p):
                add("warning", "index-dead-entry", idx_rel, f"Entry `{u}` points to a missing file.")
    elif rel_dir == "":
        add("info", "no-root-index", idx_rel, "No root index.md; run `okf.py index` to add one and declare okf_version (spec 8, 12).")
    if log_rel in b.docs:
        d = b.docs[log_rel]
        if d.has_fm:
            add("warning", "log-frontmatter", log_rel, "log.md should have no frontmatter (spec 9).", 1)
        s = strip_code(d.body)
        dates = []
        for m in re.finditer(r"^##[ \t]+(.+?)[ \t]*$", s, re.M):
            h = m.group(1).strip()
            line = d.body_line + s.count("\n", 0, m.start())
            if not DATE_RE.match(h):
                add("error", "log-bad-date", log_rel, f"Log date headings MUST be YYYY-MM-DD (got `## {h}`) (spec 9).", line)
            else:
                dates.append(h)
        if dates != sorted(dates, reverse=True):
            add("warning", "log-order", log_rel, "Log entries should be newest first (spec 9).")


def _summary(b, findings, now):
    concepts = b.concepts()
    fms = {r: fm_dict(d) for r, d in concepts.items()}
    root_idx = b.docs.get("index.md")
    version = fm_dict(root_idx).get("okf_version") if root_idx else None
    sev = Counter(f.severity for f in findings)
    stale = sorted(r for r, fm in fms.items() if (dt := parse_dt(fm.get("stale_after"))) and now >= dt)
    return {
        "root": b.root,
        "okf_version": None if version is None else str(version),
        "conformant": sev["error"] == 0,
        "concepts": len(concepts),
        "errors": sev["error"],
        "warnings": sev["warning"],
        "info": sev["info"],
        "by_type": dict(Counter(str(fm.get("type") or "(none)") for fm in fms.values()).most_common()),
        "trust_tiers": dict(Counter(trust_tier(fm) for fm in fms.values())),
        "status": dict(Counter(str(fm.get("status", "stable")) for fm in fms.values())),
        "stale": stale,
        "attested_computations": sum(1 for fm in fms.values() if fm.get("type") == AC_TYPE),
        "with_sources": sum(1 for fm in fms.values() if fm.get("sources")),
        "with_generated": sum(1 for fm in fms.values() if fm.get("generated")),
        "directories_without_index": sum(1 for r in b.dirs if b.subtree_concepts(r) and rjoin(r, "index.md") not in b.docs),
    }


def cmd_audit(a):
    b = Bundle(a.root, a.exclude)
    now = parse_dt(a.now) if a.now else now_utc()
    findings, summary = audit(b, now)
    if a.json:
        print(json.dumps({"summary": summary, "findings": [asdict(f) for f in findings]}, indent=2))
    else:
        _print_audit(summary, findings, a.min_severity, a.max_per_code)
    if summary["errors"] or (a.strict and summary["warnings"]):
        return 1
    return 0


def _print_audit(s, findings, min_sev, max_per_code):
    verdict = "CONFORMANT" if s["conformant"] else "NOT CONFORMANT"
    print(f"OKF audit: {s['root']}  (okf_version: {s['okf_version'] or 'undeclared'})")
    print(f"  {s['concepts']} concepts | {s['errors']} errors | {s['warnings']} warnings | {s['info']} info -> {verdict} (OKF v{OKF_VERSION}, spec 11)")
    if s["by_type"]:
        print("  types:  " + ", ".join(f"{k} {v}" for k, v in s["by_type"].items()))
    print("  trust:  " + ", ".join(f"{k} {s['trust_tiers'].get(k, 0)}" for k in ("unverified", "machine-confirmed", "human-reviewed")))
    print("  status: " + ", ".join(f"{k} {v}" for k, v in s["status"].items()) + f" | stale {len(s['stale'])}")
    print(f"  provenance: {s['with_sources']} with sources, {s['with_generated']} with generated | "
          f"attested computations {s['attested_computations']} | dirs without index.md {s['directories_without_index']}")
    shown = [f for f in findings if SEV_ORDER[f.severity] <= SEV_ORDER[min_sev]]
    per_code, hidden = Counter(), Counter()
    current = None
    for f in shown:
        per_code[f.code] += 1
        if max_per_code and per_code[f.code] > max_per_code:
            hidden[f.code] += 1
            continue
        if f.severity != current:
            current = f.severity
            print(f"\n{f.severity.upper()}S")
        loc = f"{f.path}:{f.line}" if f.line else f.path
        print(f"  {loc}  [{f.code}] {f.message}")
    for code, n in sorted(hidden.items()):
        print(f"  ... and {n} more [{code}] (use --json or --max-per-code 0 for all)")
    below = len(findings) - len(shown)
    if below:
        print(f"\n({below} lower-severity findings hidden; use --min-severity info)")


