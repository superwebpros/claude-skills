def main(argv=None):
    p = argparse.ArgumentParser(prog="okf.py", description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)

    def with_root(sp):
        sp.add_argument("root", help="bundle root directory")
        sp.add_argument("--exclude", action="append", default=[], metavar="GLOB",
                        help="skip files/dirs matching GLOB (repeatable; dot-dirs and node_modules are always skipped)")

    s = sub.add_parser("audit", help="check conformance and lint")
    with_root(s)
    s.add_argument("--json", action="store_true", help="machine-readable output (all findings)")
    s.add_argument("--strict", action="store_true", help="exit 1 on warnings too")
    s.add_argument("--min-severity", choices=["error", "warning", "info"], default="warning")
    s.add_argument("--max-per-code", type=int, default=15, help="cap printed findings per code (0 = no cap)")
    s.add_argument("--now", help="override 'now' for staleness (ISO 8601 with offset)")
    s.set_defaults(fn=cmd_audit)

    s = sub.add_parser("index", help="generate/refresh index.md files")
    with_root(s)
    s.add_argument("--group-by", choices=["none", "type"], default="none")
    s.add_argument("--okf-version", help=f"okf_version for the root index (default: keep existing, else {OKF_VERSION})")
    s.add_argument("--no-version", action="store_true", help="don't declare okf_version")
    s.add_argument("--force", action="store_true", help="overwrite hand-curated index.md files too")
    s.add_argument("--check", action="store_true", help="don't write; exit 1 if any index is out of date")
    s.set_defaults(fn=cmd_index)

    s = sub.add_parser("init", help="scaffold a bundle")
    s.add_argument("root")
    s.add_argument("--okf-version", default=OKF_VERSION)
    s.add_argument("--date", help="YYYY-MM-DD for the initialization log entry")
    s.set_defaults(fn=cmd_init)

    s = sub.add_parser("new", help="create a concept")
    s.add_argument("root")
    s.add_argument("path", help="concept path relative to root, e.g. playbooks/freshness-alert.md")
    s.add_argument("--type", required=True)
    s.add_argument("--title")
    s.add_argument("--description")
    s.add_argument("--resource")
    s.add_argument("--tags", help="comma-separated")
    s.add_argument("--status", choices=STATUSES)
    s.add_argument("--by", help="actor for generated.by: <producer>/<version>, human:<id>, or process:<id>")
    s.add_argument("--stale-after", help="ISO 8601 datetime with offset")
    s.add_argument("--runtime", help="required for Attested Computation")
    s.add_argument("--log", action="store_true", help="add a Creation entry to the root log.md")
    s.set_defaults(fn=cmd_new)

    s = sub.add_parser("log", help="add a log.md entry")
    s.add_argument("root")
    s.add_argument("--dir", help="directory (relative to root) whose log.md to write; default root")
    s.add_argument("--kind", default="Update", help="leading bold word, e.g. Update, Creation, Deprecation")
    s.add_argument("--message", required=True)
    s.add_argument("--date")
    s.set_defaults(fn=cmd_log)

    s = sub.add_parser("plan", help="propose edits to make a folder conformant")
    with_root(s)
    s.add_argument("--out", help="write plan JSON here (default: stdout)")
    s.add_argument("--rule", action="append", default=[], metavar="GLOB=Type", help="force a type for matching paths (repeatable, first wins)")
    s.add_argument("--default-type", default="Reference", help="type when nothing else matches (default: Reference)")
    s.add_argument("--by", help="actor to record in generated.by (omit to skip provenance)")
    s.set_defaults(fn=cmd_plan)

    s = sub.add_parser("apply", help="apply a reviewed plan")
    s.add_argument("plan")
    s.add_argument("--root", help="override the root recorded in the plan")
    s.add_argument("--dry-run", action="store_true")
    s.set_defaults(fn=cmd_apply)

    a = p.parse_args(argv)
    return a.fn(a)


