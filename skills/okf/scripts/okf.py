"""okf.py - configure, audit, and adapt folders as Open Knowledge Format (OKF) v0.2 bundles.

Spec: https://github.com/GoogleCloudPlatform/knowledge-catalog/blob/main/okf/SPEC.md

Commands:
  init  ROOT              Scaffold a bundle (root index.md declaring okf_version, log.md).
  new   ROOT PATH         Create a concept with valid frontmatter (templates per type).
  index ROOT              Generate/refresh index.md files from concept frontmatter.
  log   ROOT              Add a dated entry to a log.md (newest-first).
  audit ROOT              Conformance (spec section 11) + lint of SHOULD-level guidance.
  plan  ROOT              Survey an existing folder; write a reviewable JSON plan of edits.
  apply PLAN              Apply a (reviewed) plan. Use --dry-run first.

Run with `uv run scripts/okf.py ...` (PyYAML installed automatically) or plain
`python3` when PyYAML is available.
"""
